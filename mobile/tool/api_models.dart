/// How one schema reads in Dart: [dart] is the non-null type, and [read]
/// converts a raw JSON value into `dart?`.
class _Type {
  const _Type(this.dart, this._template);

  final String dart;

  /// The conversion, with `#` standing for the value.
  final String _template;

  String read(String value) => _template.replaceAll('#', value);

  /// The conversion as a function of one value, for a list or map item.
  String get function =>
      RegExp(r'^(\w+)\(#\)$').firstMatch(_template)?.group(1) ??
      '(v) => ${read('v')}';

  bool get isAny => dart == 'Object';
  bool get isJsonObject => dart == 'Map<String, dynamic>';
}

const _string = _Type('String', '_string(#)');
const _int = _Type('int', '_int(#)');
const _double = _Type('double', '_double(#)');
const _bool = _Type('bool', '_bool(#)');
const _any = _Type('Object', '_any(#)');
const _jsonObject = _Type('Map<String, dynamic>', '_json(#)');

/// The type of an enum that only allows null: spectacular's `NullEnum`.
const _null = _Type('Null', '_any(#)');

class _Generator {
  _Generator(Map<String, dynamic> schema)
    : _paths = Map<String, dynamic>.from(schema['paths'] as Map),
      _components = Map<String, dynamic>.from(
        (schema['components'] as Map?)?['schemas'] as Map? ?? const {},
      );

  final Map<String, dynamic> _paths;
  final Map<String, dynamic> _components;

  String library() {
    final out = StringBuffer()
      ..writeln('// GENERATED by tool/api_models.dart from the API\'s OpenAPI')
      ..writeln('// schema. Do not edit; rerun the tool after an API change.')
      ..writeln('//')
      ..writeln(
        '// Every field is nullable and a value of the wrong type reads',
      )
      ..writeln('// as null, so an older or newer server degrades the way')
      ..writeln(
        '// hand-written parsing did. lib/data/models/ decides defaults.',
      )
      ..writeln(
        '// ignore_for_file: non_constant_identifier_names, unused_element',
      )
      ..writeln()
      ..writeln(_operations());
    for (final name in _classNames()) {
      out.writeln(_class(name));
    }
    out.write(_helpers);
    return '$out';
  }

  /// `{path: {METHOD: body fields}}`, a null field set meaning the body is
  /// free-form and an empty one that the operation takes no body.
  String _operations() {
    final out = StringBuffer()
      ..writeln('/// Every operation the API publishes, with the body fields')
      ..writeln(
        '/// each accepts (`null`: any). `lib/services/api_contract.dart`',
      )
      ..writeln('/// holds requests to it in debug builds and tests.')
      ..writeln(
        'const Map<String, Map<String, Set<String>?>> apiOperations = {',
      );
    for (final path in _paths.keys.toList()..sort()) {
      final operations = _paths[path] as Map;
      out.writeln('  ${_literal(path)}: {');
      for (final method in _methods) {
        final operation = operations[method];
        if (operation is! Map) continue;
        final fields = _bodyFields(operation);
        out.writeln(
          "    '${method.toUpperCase()}': "
          '${fields == null ? 'null' : '<String>{${fields.map(_literal).join(', ')}}'},',
        );
      }
      out.writeln('  },');
    }
    out.writeln('};');
    return '$out';
  }

  List<String>? _bodyFields(Map operation) {
    final content = (operation['requestBody'] as Map?)?['content'] as Map?;
    if (content == null) return const [];
    final fields = <String>{};
    for (final media in content.values) {
      final names = _propertyNames((media as Map)['schema'] as Map?);
      if (names == null) return null;
      fields.addAll(names);
    }
    return fields.toList()..sort();
  }

  /// The property names of a request body schema, or null when it is open.
  Iterable<String>? _propertyNames(Map? schema) {
    if (schema == null) return null;
    if (schema[r'$ref'] case final String ref) {
      return _propertyNames(_components[_refName(ref)] as Map?);
    }
    final properties = schema['properties'];
    final extra = schema['additionalProperties'];
    if (properties is! Map || (extra != null && extra != false)) return null;
    return properties.keys.cast<String>();
  }

  /// Components a response can contain, directly or nested, that have fields.
  List<String> _classNames() {
    final reached = <String>{};
    final pending = <String>[];
    void collect(Object? node) {
      if (node is Map) {
        node.forEach((key, value) {
          if (key == r'$ref' && value is String) {
            pending.add(_refName(value));
          } else {
            collect(value);
          }
        });
      } else if (node is List) {
        node.forEach(collect);
      }
    }

    for (final operations in _paths.values) {
      for (final method in _methods) {
        collect((operations as Map)[method]?['responses']);
      }
    }
    while (pending.isNotEmpty) {
      final name = pending.removeLast();
      if (reached.add(name)) collect(_components[name]);
    }
    return reached.where((name) => _isClass(_components[name] as Map)).toList()
      ..sort();
  }

  bool _isClass(Map schema) =>
      schema['properties'] is Map && (schema['properties'] as Map).isNotEmpty;

  String _class(String name) {
    final properties = Map<String, dynamic>.from(
      (_components[name] as Map)['properties'] as Map,
    );
    final fields = <(String, String, _Type)>[];
    final used = <String>{};
    for (final MapEntry(:key, :value) in properties.entries) {
      var id = _identifier(key);
      while (!used.add(id)) {
        id = '${id}_';
      }
      fields.add((key, id, _typeOf(value as Map)));
    }
    final out = StringBuffer()
      ..writeln('class ${_dartName(name)} {')
      ..writeln(
        '  const ${_dartName(name)}'
        '(this.json, {${fields.map((f) => 'this.${f.$2}').join(', ')}});',
      )
      ..writeln()
      ..writeln(
        '  factory ${_dartName(name)}.fromJson(Map<String, dynamic> json) => '
        '${_dartName(name)}(json,',
      );
    for (final (key, id, type) in fields) {
      out.writeln('    $id: ${type.read('json[${_literal(key)}]')},');
    }
    out
      ..writeln('  );')
      ..writeln()
      ..writeln(
        '  /// The object as received, for handing it to its own model.',
      )
      ..writeln('  final Map<String, dynamic> json;');
    for (final (_, id, type) in fields) {
      out.writeln('  final ${type.dart}? $id;');
    }
    out.writeln('}');
    return '$out';
  }

  _Type _typeOf(Map schema) {
    if (schema[r'$ref'] case final String ref) return _named(_refName(ref));
    for (final key in ['allOf', 'oneOf', 'anyOf']) {
      if (schema[key] case final List members) {
        final types = [
          for (final member in members)
            if (_typeOf(member as Map) case final type when type != _null) type,
        ];
        if (types.isEmpty) return _any;
        if (types.every((t) => t.dart == types.first.dart)) return types.first;
        if (types.every((t) => t.isJsonObject || _isClassName(t.dart))) {
          return _jsonObject;
        }
        return _any;
      }
    }
    switch (schema['type']) {
      case 'string':
        return schema['format'] == 'binary' ? _any : _string;
      case 'integer':
        return _int;
      case 'number':
        return _double;
      case 'boolean':
        return _bool;
      case 'array':
        final item = _typeOf(schema['items'] as Map? ?? const {});
        return _Type('List<${item.dart}>', '_list(#, ${item.function})');
      case 'object':
        final extra = schema['additionalProperties'];
        if (schema['properties'] == null && extra is Map && extra.isNotEmpty) {
          final item = _typeOf(extra);
          if (!item.isAny) {
            return _Type(
              'Map<String, ${item.dart}>',
              '_map(#, ${item.function})',
            );
          }
        }
        return _jsonObject;
    }
    return _any;
  }

  _Type _named(String name) {
    final schema = _components[name] as Map;
    if (schema['enum'] case final List values) {
      if (values.every((v) => v == null)) return _null;
      return values.every((v) => v == null || v is int) ? _int : _string;
    }
    if (_isClass(schema)) {
      final dart = _dartName(name);
      return _Type(dart, '_object(#, $dart.fromJson)');
    }
    return _typeOf(schema);
  }

  bool _isClassName(String dart) => _components.entries.any(
    (c) => _dartName(c.key) == dart && _isClass(c.value as Map),
  );
}

/// A component name as a public Dart class name: a serializer named
/// `_KanbanLineItem` publishes `KanbanLineItem`.
String _dartName(String component) => component.replaceFirst(RegExp('^_+'), '');

String _refName(String ref) => ref.split('/').last;

/// `first_name` reads as `firstName`; a reserved word or a leading digit gets
/// a suffix or prefix so it is a valid Dart identifier.
String _identifier(String key) {
  final parts = key.split('_').where((p) => p.isNotEmpty).toList();
  if (parts.isEmpty) return 'value_';
  var id = parts.first[0].toLowerCase() + parts.first.substring(1);
  for (final part in parts.skip(1)) {
    id += part[0].toUpperCase() + part.substring(1);
  }
  if (RegExp(r'^[0-9]').hasMatch(id)) id = 'v$id';
  return _reserved.contains(id) ? '${id}_' : id;
}

String _literal(String value) =>
    "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

const _helpers = r'''
String? _string(Object? v) => v is String ? v : (v is num ? '$v' : null);

int? _int(Object? v) => v is num ? v.toInt() : null;

double? _double(Object? v) => v is num ? v.toDouble() : null;

bool? _bool(Object? v) => v is bool ? v : null;

Object? _any(Object? v) => v;

Map<String, dynamic>? _json(Object? v) => v is Map<String, dynamic> ? v : null;

T? _object<T>(Object? v, T Function(Map<String, dynamic>) fromJson) =>
    v is Map<String, dynamic> ? fromJson(v) : null;

List<T>? _list<T extends Object>(Object? v, T? Function(Object?) item) =>
    v is List ? [for (final e in v) ?item(e)] : null;

Map<String, T>? _map<T extends Object>(Object? v, T? Function(Object?) item) =>
    v is Map
    ? {
        for (final MapEntry(:key, :value) in v.entries)
          if (item(value) case final T x) '$key': x,
      }
    : null;
''';
