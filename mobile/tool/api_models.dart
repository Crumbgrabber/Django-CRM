// Writes the app's API wire types from the backend's OpenAPI schema.
//
//   dart run tool/api_models.dart          # ../backend's schema, into lib/data/api/schema.g.dart
//   dart run tool/api_models.dart --schema openapi.json --out lib/data/api/x.g.dart
//
// Run it after any API change and commit the result. enterprise-crm's
// deploy/web-api-types.sh writes lib/data/api/enterprise_schema.g.dart with it.
import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> args) async {
  final options = <String, String>{
    for (var i = 0; i + 1 < args.length; i += 2)
      args[i].replaceFirst('--', ''): args[i + 1],
  };
  final out = options['out'] ?? 'lib/data/api/schema.g.dart';
  final tmp = Directory.systemTemp.createTempSync('api_models');
  try {
    var schemaPath = options['schema'];
    if (schemaPath == null) {
      schemaPath = '${tmp.path}/openapi.json';
      await _run('uv', [
        'run',
        '--directory',
        '../backend',
        'python',
        'manage.py',
        'spectacular',
        '--format',
        'openapi-json',
        '--file',
        schemaPath,
      ]);
    }
    final schema = jsonDecode(File(schemaPath).readAsStringSync());
    File(out)
      ..createSync(recursive: true)
      ..writeAsStringSync(_Generator(schema as Map<String, dynamic>).library());
    await _run('dart', ['format', out]);
  } finally {
    tmp.deleteSync(recursive: true);
  }
}

Future<void> _run(String command, List<String> args) async {
  final result = await Process.run(command, args);
  if (result.exitCode != 0) {
    stderr
      ..write(result.stdout)
      ..write(result.stderr);
    exit(result.exitCode);
  }
}

